using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.ChangeTracking;
using Microsoft.EntityFrameworkCore.Infrastructure;
using Nexus.Domain.Catalog;
using Nexus.Domain.Customers;
using Nexus.Domain.Files;
using Nexus.Domain.Tenancy;

namespace Nexus.Application.Abstractions;

/// <summary>The authenticated caller, taken from the validated session (never from the request body).</summary>
public interface ICurrentUser
{
    /// <summary><see cref="Guid.Empty"/> when the request is anonymous or runs outside HTTP.</summary>
    Guid UserId { get; }
}

/// <summary>Request facts that audit entries and sessions record. All optional: background work has none.</summary>
public interface IRequestInfo
{
    string? CorrelationId { get; }

    /// <summary>Client IP truncated to /24 (IPv4) or /48 (IPv6); the full address is never stored.</summary>
    string? IpPrefix { get; }
}

/// <summary>The single unit of work (ADR-0001). Tenant-owned sets are filtered to the current tenant.</summary>
public interface IAppDbContext
{
    DbSet<Tenant> Tenants { get; }

    DbSet<Role> Roles { get; }

    DbSet<RolePermission> RolePermissions { get; }

    DbSet<Membership> Memberships { get; }

    DbSet<Invitation> Invitations { get; }

    DbSet<Customer> Customers { get; }

    DbSet<CustomerTag> CustomerTags { get; }

    DbSet<CustomerNote> CustomerNotes { get; }

    DbSet<Tag> Tags { get; }

    DbSet<ProductCategory> ProductCategories { get; }

    DbSet<Product> Products { get; }

    DbSet<StoredFile> StoredFiles { get; }

    /// <summary>Needed to set the expected concurrency version of an entity before saving it.</summary>
    EntityEntry<TEntity> Entry<TEntity>(TEntity entity) where TEntity : class;

    DatabaseFacade Database { get; }

    ChangeTracker ChangeTracker { get; }

    Task<int> SaveChangesAsync(CancellationToken ct = default);
}

/// <summary>Provider-specific database operations the use cases need without referencing Npgsql.</summary>
public interface IDatabaseTools
{
    /// <summary>
    /// <c>SELECT … FOR UPDATE</c> on the tenant row inside the current transaction: serialises operations that must
    /// keep a company-wide invariant (at least one active Owner).
    /// </summary>
    Task LockTenantAsync(Guid tenantId, CancellationToken ct);

    /// <summary>
    /// Transaction-scoped advisory lock on an arbitrary key (<c>pg_advisory_xact_lock</c>): serialises check-then-insert
    /// rules that a unique index cannot express, such as "no duplicate customer by e-mail or tax id".
    /// </summary>
    Task LockAsync(string key, CancellationToken ct);

    /// <summary>True when <paramref name="exception"/> is a unique violation of <paramref name="constraint"/>.</summary>
    bool IsUniqueViolation(Exception exception, string constraint);
}

public sealed record UserSummary(Guid Id, string Email, string DisplayName, bool EmailConfirmed);

/// <summary>Read access to user accounts, which live in the identity store (Infrastructure).</summary>
public interface IUserDirectory
{
    Task<UserSummary?> FindAsync(Guid userId, CancellationToken ct);

    Task<IReadOnlyDictionary<Guid, UserSummary>> GetManyAsync(IEnumerable<Guid> userIds, CancellationToken ct);

    Task<Guid?> FindIdByEmailAsync(string email, CancellationToken ct);

    /// <summary>The same normalisation the identity store applies, so invitations and accounts compare equal.</summary>
    string NormalizeEmail(string email);
}

/// <summary>
/// Explicit audit records (ADR-0009), added to the current unit of work: they are saved, or discarded, together
/// with the change they describe. Metadata must come from an allow-list: never passwords, tokens or free text.
/// </summary>
public interface IAuditLog
{
    /// <summary>An event inside the current tenant, attributed to the current user.</summary>
    void Tenant(string action, string entityType, Guid entityId, object? metadata = null);

    /// <summary>An account security event (no tenant). <paramref name="userId"/> is null for unknown accounts.</summary>
    void Account(string action, Guid? userId, object? metadata = null);
}

/// <summary>Queues an e-mail in the outbox of the current unit of work; a background service delivers it.</summary>
public interface IEmailOutbox
{
    void Enqueue(string recipient, string subject, string textBody);
}

/// <summary>Absolute links to the web app for e-mails, and the configured commercial name.</summary>
public interface IAppLinks
{
    string ProductName { get; }

    string VerifyEmail(Guid userId, string token);

    string ResetPassword(Guid userId, string token);

    string Invitation(Guid tenantId, string token);
}

/// <summary>
/// Where uploaded bytes live (local folder or volume in v1; object storage later). Keys are generated by the server
/// (<see cref="Domain.Files.StoredFile.StorageKey"/>), never derived from client input.
/// </summary>
public interface IFileStorage
{
    Task SaveAsync(string key, ReadOnlyMemory<byte> content, CancellationToken ct);

    /// <returns>The content, or null when the file is missing.</returns>
    Task<Stream?> OpenAsync(string key, CancellationToken ct);

    Task DeleteAsync(string key, CancellationToken ct);
}
