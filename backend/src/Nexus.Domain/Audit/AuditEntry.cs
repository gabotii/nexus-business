namespace Nexus.Domain.Audit;

public enum AuditActorType
{
    User,
    System,
    Anonymous,
}

/// <summary>
/// One append-only audit record (ADR-0009). <see cref="TenantId"/> is null for account security events (sign-in,
/// password changes). <see cref="Metadata"/> is JSON built from a per-action allow-list: never passwords, tokens,
/// request bodies or free text.
/// </summary>
public sealed class AuditEntry
{
    private AuditEntry()
    {
        Action = string.Empty;
    }

    public AuditEntry(Guid id, Guid? tenantId, Guid? actorUserId, AuditActorType actorType, string action, string? entityType,
        string? entityId, DateTimeOffset occurredAt, string? correlationId, string? ipPrefix, string? metadata)
    {
        Id = id;
        TenantId = tenantId;
        ActorUserId = actorUserId;
        ActorType = actorType;
        Action = action;
        EntityType = entityType;
        EntityId = entityId;
        OccurredAt = occurredAt;
        CorrelationId = correlationId;
        IpPrefix = ipPrefix;
        Metadata = metadata;
    }

    /// <summary>
    /// UUID v7 generated by the application (time-ordered). Not a database identity: inserts then need no
    /// <c>RETURNING</c>, which Row-Level Security would otherwise check against the read policy.
    /// </summary>
    public Guid Id { get; private set; }

    public Guid? TenantId { get; private set; }

    public Guid? ActorUserId { get; private set; }

    public AuditActorType ActorType { get; private set; }

    /// <summary>Stable dotted name, e.g. <c>members.role_changed</c>.</summary>
    public string Action { get; private set; }

    public string? EntityType { get; private set; }

    public string? EntityId { get; private set; }

    public DateTimeOffset OccurredAt { get; private set; }

    public string? CorrelationId { get; private set; }

    /// <summary>Client IP truncated to /24 (IPv4) or /48 (IPv6).</summary>
    public string? IpPrefix { get; private set; }

    public string? Metadata { get; private set; }
}
